"""On-disk response cache, keyed by a hash of everything that affects the answer.

Dev-tooling item 2. Iterating on Phase 1-4 logic re-runs the mentor constantly,
and without this every run is a paid API call for an answer that has not
changed. The key covers the model and prompt as well as the payload, so editing
the system prompt correctly misses the cache instead of silently returning
coaching generated by the old wording.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

from ..config import CACHE_DIR

MENTOR_CACHE = CACHE_DIR / "mentor"


def key_for(model: str, system: str, payload: str, **extra) -> str:
    h = hashlib.sha256()
    for part in (model, system, payload, json.dumps(extra, sort_keys=True)):
        h.update(part.encode("utf-8"))
        h.update(b"\x00")          # delimiter: prevents field-boundary collisions
    return h.hexdigest()[:32]


def load(key: str) -> dict | None:
    p = MENTOR_CACHE / f"{key}.json"
    if not p.exists():
        return None
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except Exception:
        return None                # a corrupt entry is a miss, never an error


def save(key: str, record: dict) -> Path:
    MENTOR_CACHE.mkdir(parents=True, exist_ok=True)
    p = MENTOR_CACHE / f"{key}.json"
    p.write_text(json.dumps(record, indent=2, ensure_ascii=False), encoding="utf-8")
    return p


def clear() -> int:
    if not MENTOR_CACHE.exists():
        return 0
    n = 0
    for p in MENTOR_CACHE.glob("*.json"):
        p.unlink()
        n += 1
    return n


def stats() -> tuple[int, int]:
    """(entries, total_bytes)"""
    if not MENTOR_CACHE.exists():
        return 0, 0
    files = list(MENTOR_CACHE.glob("*.json"))
    return len(files), sum(f.stat().st_size for f in files)
